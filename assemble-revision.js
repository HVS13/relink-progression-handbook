const fs=require('node:fs'),vm=require('node:vm');
const data=require('./revision-data.json');
let shell=fs.readFileSync('handbook-template.html','utf8');
shell=shell.replace('<title>Relink Defender Field Guide — All Character Progression</title>','<title>Relink Defender Field Guide — Revised 28-Character Edition</title>');
shell=shell.replace('Party-wide Summons','Summons · personal passive bonuses');
shell=shell.replace('Competitive specialization index','Character-specific starting paths').replace('28 Master Style starting paths','28 researched character playstyles');
